/**
 * The main theme composable for the DroidCalc application.
 * This function applies the Material 3 theme, supporting dynamic coloring on Android 12+,
 * and falling back to predefined [LightColors] or [DarkColors].
 * It also sets the system bar colors to match the theme.
 *
 * @param darkTheme Whether the theme should be dark or light. Defaults to the system's dark theme setting.
 * @param dynamicColor Whether to use dynamic coloring (Monet) on Android 12+. Defaults to true.
 *                     Dynamic color is only available on API 31+.
 * @param content The composable content to which the theme will be applied.
 * @author DroidSwap
 */
@Composable
fun CalcTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true, // Enable dynamic color support
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            window.statusBarColor = colorScheme.background.toArgb() // Use background for status bar
            window.navigationBarColor = colorScheme.background.toArgb() // Use background for navigation bar
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
            WindowCompat.getInsetsController(window, view).isAppearanceLightNavigationBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography, // Defined in Type.kt
        // shapes = Shapes, // Can be defined in a Shapes.kt file if needed
        content = content
    )
}
